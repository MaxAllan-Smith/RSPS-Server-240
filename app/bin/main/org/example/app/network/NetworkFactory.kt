@file:OptIn(ExperimentalUnsignedTypes::class)

package org.example.app.network

import net.rsprot.compression.provider.HuffmanCodecProvider
import net.rsprot.crypto.rsa.RsaKeyPair
import net.rsprot.protocol.api.AbstractNetworkServiceFactory
import net.rsprot.protocol.api.GameConnectionHandler
import net.rsprot.protocol.api.js5.Js5GroupProvider
import net.rsprot.protocol.common.client.OldSchoolClientType
import net.rsprot.protocol.game.incoming.misc.client.MapBuildComplete
import net.rsprot.protocol.message.codec.incoming.GameMessageConsumerRepository
import net.rsprot.protocol.message.codec.incoming.GameMessageConsumerRepositoryBuilder
import net.rsprot.protocol.message.codec.incoming.provider.GameMessageConsumerRepositoryProvider
import org.example.app.config.ServerConfig
import org.example.app.player.Player

class NetworkFactory(
    private val rsaKey: RsaKeyPair,
    private val huffmanProvider: HuffmanCodecProvider,
    private val js5Provider: Js5GroupProvider,
    private val connectionHandler: GameConnectionHandler<Player>,
) : AbstractNetworkServiceFactory<Player>() {

    override val host: String =
        ServerConfig.HOST

    override val ports: List<Int> =
        listOf(
            ServerConfig.PORT
        )

    override val supportedClientTypes:
        List<OldSchoolClientType> =
        listOf(
            OldSchoolClientType.DESKTOP
        )

    /*
     * Register the incoming packets that the game engine currently
     * understands.
     *
     * MAP_BUILD_COMPLETE is particularly useful during login because
     * the official client sends it after the scene generated by
     * RebuildLoginV2 has finished loading.
     */
    private val gameMessages:
        GameMessageConsumerRepository<Player> =
        GameMessageConsumerRepositoryBuilder<Player>()
            .addListener<MapBuildComplete> { _ ->
                if (!mapBuildComplete) {
                    mapBuildComplete =
                        true

                    println(
                        "[Map] '${username}' finished building " +
                            "the game world at " +
                            "${position.x}," +
                            "${position.z}," +
                            "${position.level}."
                    )
                }
            }
            .build()

    override fun getRsaKeyPair():
        RsaKeyPair {
        return rsaKey
    }

    override fun getHuffmanCodecProvider():
        HuffmanCodecProvider {
        return huffmanProvider
    }

    override fun getJs5GroupProvider():
        Js5GroupProvider {
        return js5Provider
    }

    override fun getGameMessageConsumerRepositoryProvider():
        GameMessageConsumerRepositoryProvider<Player> {
        return GameMessageConsumerRepositoryProvider {
            gameMessages
        }
    }

    override fun getGameConnectionHandler():
        GameConnectionHandler<Player> {
        return connectionHandler
    }
}